#!/usr/bin/env bash
# Writes an ippeveprinter attributes file that declares the paper sizes as
# supported AND loaded (ready), the way a real AirPrint printer does.
#   make_attrs.sh "Letter,Legal" "Printer name" color(true|false) duplex(true|false) > attrs.conf
# (ippeveprinter does not allow -M/-m/-s/-f together with -a, so everything
# about the printer is declared here.)
set -uo pipefail

SIZES="${1:-Letter}"
MAKE_MODEL="${2:-Printer}"
COLOR="${3:-false}"
DUPLEX="${4:-false}"

URF="V1.4,CP1,PQ4,RS600,W8"; PWG="black_1,sgray_8"
CMODES="monochrome"; CDEFAULT="monochrome"; CSUP=false
if [ "$COLOR" = "true" ]; then
  URF="${URF},SRGB24"; PWG="${PWG},srgb_8"; CMODES="monochrome,color"; CDEFAULT="color"; CSUP=true
fi
SIDES="one-sided"
[ "$DUPLEX" = "true" ] && SIDES="one-sided,two-sided-long-edge,two-sided-short-edge" && URF="${URF},DM1"
FIRST=""
KW=(); COLS=(); SIZECOLS=()

col() { # x y source
  printf '{\n    MEMBER collection media-size {\n      MEMBER integer x-dimension %s\n      MEMBER integer y-dimension %s\n    }\n    MEMBER integer media-bottom-margin 500\n    MEMBER integer media-left-margin 500\n    MEMBER integer media-right-margin 500\n    MEMBER integer media-top-margin 500\n    MEMBER keyword media-source "%s"\n    MEMBER keyword media-type "stationery"\n  }' "$1" "$2" "$3"
}

for s in ${SIZES//,/ }; do
  case "$s" in
    Letter) kw=na_letter_8.5x11in;  x=21590; y=27940 ;;
    Legal)  kw=na_legal_8.5x14in;   x=21590; y=35560 ;;
    A4)     kw=iso_a4_210x297mm;    x=21000; y=29700 ;;
    A5)     kw=iso_a5_148x210mm;    x=14800; y=21000 ;;
    *) continue ;;
  esac
  [ -z "$FIRST" ] && FIRST="$kw" && FX=$x && FY=$y
  KW+=("$kw")
  COLS+=("$(col "$x" "$y" auto)")
  SIZECOLS+=("$(printf '{\n    MEMBER integer x-dimension %s\n    MEMBER integer y-dimension %s\n  }' "$x" "$y")")
done

[ -z "$FIRST" ] && { echo "No usable paper sizes in '$SIZES'" >&2; exit 1; }

join() { local IFS=","; echo "$*"; }

cat <<EOF
# Generated by airprint_bridge: paper sizes = ${SIZES}
ATTR text printer-make-and-model "${MAKE_MODEL}"
ATTR mimeMediaType document-format-supported application/pdf,image/jpeg,image/png,image/pwg-raster,image/urf
ATTR mimeMediaType document-format-default application/pdf
ATTR keyword urf-supported ${URF}
ATTR resolution pwg-raster-document-resolution-supported 600dpi
ATTR keyword pwg-raster-document-type-supported ${PWG}
ATTR resolution printer-resolution-supported 600dpi
ATTR resolution printer-resolution-default 600dpi
ATTR boolean color-supported ${CSUP}
ATTR keyword print-color-mode-supported ${CMODES}
ATTR keyword print-color-mode-default ${CDEFAULT}
ATTR keyword sides-supported ${SIDES}
ATTR keyword sides-default one-sided
ATTR enum print-quality-supported 4,5
ATTR enum print-quality-default 4
ATTR integer pages-per-minute 20
ATTR rangeOfInteger copies-supported 1-99
ATTR integer copies-default 1
ATTR keyword media-supported $(join "${KW[@]}")
ATTR keyword media-ready $(join "${KW[@]}")
ATTR keyword media-default ${FIRST}
ATTR keyword media-source-supported auto
ATTR keyword media-type-supported stationery
ATTR keyword media-col-supported media-bottom-margin,media-left-margin,media-right-margin,media-size,media-source,media-top-margin,media-type
ATTR integer media-bottom-margin-supported 500
ATTR integer media-left-margin-supported 500
ATTR integer media-right-margin-supported 500
ATTR integer media-top-margin-supported 500
ATTR collection media-col-default $(col "$FX" "$FY" auto)
EOF
# ippeveprinter checks a job's media-col size against media-size-supported.
printf 'ATTR collection media-size-supported '
first=1; for c in "${SIZECOLS[@]}"; do [ $first -eq 1 ] || printf ','; printf '%s' "$c"; first=0; done; echo
printf 'ATTR collection media-col-ready '
first=1; for c in "${COLS[@]}"; do [ $first -eq 1 ] || printf ','; printf '%s' "$c"; first=0; done; echo
printf 'ATTR collection media-col-database '
first=1; for c in "${COLS[@]}"; do [ $first -eq 1 ] || printf ','; printf '%s' "$c"; first=0; done; echo
