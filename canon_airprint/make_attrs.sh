#!/usr/bin/env bash
# Writes an ippeveprinter attributes file that declares the paper sizes as
# supported AND loaded (ready), the way a real AirPrint printer does.
#   make_attrs.sh "Letter,Legal" > attrs.conf
set -uo pipefail

SIZES="${1:-Letter}"
FIRST=""
KW=(); COLS=()

col() { # x y source
  printf '{\n    MEMBER collection media-size {\n      MEMBER integer x-dimension %s\n      MEMBER integer y-dimension %s\n    }\n    MEMBER integer media-bottom-margin 500\n    MEMBER integer media-left-margin 500\n    MEMBER integer media-right-margin 500\n    MEMBER integer media-top-margin 500\n    MEMBER keyword media-source "%s"\n    MEMBER keyword media-type "stationery"\n  }' "$1" "$2" "$3"
}

for s in ${SIZES//,/ }; do
  case "$s" in
    Letter) kw=na_letter_8.5x11in;  x=21590; y=27940 ;;
    Legal)  kw=na_legal_8.5x14in;   x=21590; y=35560 ;;
    A4)     kw=iso_a4_210x297mm;    x=21000; y=29700 ;;
    A5)     kw=iso_a5_148x210mm;    x=14800; y=21000 ;;
    *) continue ;;
  esac
  [ -z "$FIRST" ] && FIRST="$kw" && FX=$x && FY=$y
  KW+=("$kw")
  COLS+=("$(col "$x" "$y" auto)")
done

[ -z "$FIRST" ] && { echo "No usable paper sizes in '$SIZES'" >&2; exit 1; }

join() { local IFS=","; echo "$*"; }

cat <<EOF
# Generated by canon_airprint: paper sizes = ${SIZES}
ATTR keyword media-supported $(join "${KW[@]}")
ATTR keyword media-ready $(join "${KW[@]}")
ATTR keyword media-default ${FIRST}
ATTR keyword media-source-supported auto
ATTR keyword media-type-supported stationery
ATTR keyword media-col-supported media-bottom-margin,media-left-margin,media-right-margin,media-size,media-source,media-top-margin,media-type
ATTR integer media-bottom-margin-supported 500
ATTR integer media-left-margin-supported 500
ATTR integer media-right-margin-supported 500
ATTR integer media-top-margin-supported 500
ATTR collection media-col-default $(col "$FX" "$FY" auto)
EOF
printf 'ATTR collection media-col-ready '
first=1; for c in "${COLS[@]}"; do [ $first -eq 1 ] || printf ','; printf '%s' "$c"; first=0; done; echo
printf 'ATTR collection media-col-database '
first=1; for c in "${COLS[@]}"; do [ $first -eq 1 ] || printf ','; printf '%s' "$c"; first=0; done; echo
